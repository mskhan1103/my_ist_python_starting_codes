# Write a lambda function to add two numbers and print the result.

a=lambda x,y:x+y
print(a(30,60))


# Use a lambda function to check if a number is even or odd.

b=lambda x: "even" if x%2==0 else "odd"

print(b(10))


# Write a lambda function to return the square of a number.

c=lambda x:x**2

print(c(9))


# Use a lambda function to find the maximum of two numbers.
d=lambda x,y: x if x>y else y
print(d(3,4))

